public class ObjTurnos {

    private String Identificacion;
    private String Nombre;
    private String TipoTramite;
    private int Edad;
    private int CondicionAtencionEspecial;
    private int NumTurno;
    private int Estado;
    
    public ObjTurnos() {

    }

    public String getIdentificacion() {
        return Identificacion;
    }

    public void setIdentificacion(String identificacion) {
        Identificacion = identificacion;
    }

    public String getNombre() {
        return Nombre;
    }

    public void setNombre(String nombre) {
        Nombre = nombre;
    }

    public String getTipoTramite() {
        return TipoTramite;
    }

    public void setTipoTramite(String tipoTramite) {
        TipoTramite = tipoTramite;
    }

    public int getEdad() {
        return Edad;
    }

    public void setEdad(int edad) {
        Edad = edad;
    }

    public int getCondicionAtencionEspecial() {
        return CondicionAtencionEspecial;
    }

    public void setCondicionAtencionEspecial(int condicionAtencionEspecial) {
        CondicionAtencionEspecial = condicionAtencionEspecial;
    }

    public int getNumTurno() {
        return NumTurno;
    }

    public void setNumTurno(int numTurno) {
        NumTurno = numTurno;
    }

    public int getEstado() {
        return Estado;
    }

    public void setEstado(int estado) {
        Estado = estado;
    }


}